/* Writes js/env.js — the settings the storefront reads in the browser — from frontend/.env,
   or from the host's environment variables (e.g. Vercel → Settings → Environment Variables).
   Run it after changing .env and before uploading:   node frontend/build-env.js   */
const fs = require('fs');
const path = require('path');

const KEYS = ['AVYA_API_URL', 'WHATSAPP_API_URL'];
const values = {};

const envFile = path.join(__dirname, '.env');
if (fs.existsSync(envFile)) {
  for (const raw of fs.readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#') || !line.includes('=')) continue;
    const at = line.indexOf('=');
    values[line.slice(0, at).trim()] = line.slice(at + 1).trim().replace(/^["']|["']$/g, '');
  }
}
for (const k of KEYS) if (process.env[k]) values[k] = process.env[k];   // host settings win

const env = Object.fromEntries(KEYS.filter(k => values[k]).map(k => [k, values[k]]));
const out = path.join(__dirname, 'js', 'env.js');
fs.writeFileSync(out, '/* Generated by frontend/build-env.js from .env — do not edit or commit. */\n'
  + 'window.AVYA_ENV = ' + JSON.stringify(env, null, 2) + ';\n');

console.log(env.AVYA_API_URL
  ? `env.js written — store API: ${env.AVYA_API_URL}`
  : 'env.js written without AVYA_API_URL — the site will use its built-in catalogue.');
